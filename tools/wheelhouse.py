#!/usr/bin/env python3
"""Publish a wheelhouse built by tools/build_wheelhouse.sh and record it.

    python3 tools/wheelhouse.py out python-cp311-aarch64-2026-11-20 [--upload]

Reads out/<set>/*.whl and out/report-<set>.json for each set (build, wheels, dev),
and:
  - uploads every wheel (once, even when two sets share it) as a release file of the
    given release tag (with --upload; creates the release);
  - replaces that release's python-wheel entries in manifest.json: name, version,
    sha256, size, and where it came from: `original_url` (the PyPI or project URL, for a
    wheel used as downloaded, same sha256) or `built_from` + `source_url` +
    `source_sha256` (a source archive compiled into a wheel in Debian 12 / CPython 3.11);
  - writes python/fork/requirements-<set>-arm64.lock: one line per wheel,
    `name @ <our URL> --hash=sha256:<sha256>`, which the fork's Dockerfile installs with
    `pip download --no-index --no-deps --require-hashes`.
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile

REPO = "TroyJ/frigate-build-deps"
SETS = ("build", "wheels", "dev")
FORK_TARGET = {
    "build": "docker/main/requirements-build-arm64.lock",
    "wheels": "docker/main/requirements-wheels-arm64.lock",
    "dev": "docker/main/requirements-dev-arm64.lock",
}


def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("release")
    ap.add_argument("--upload", action="store_true")
    a = ap.parse_args()

    m = json.load(open("manifest.json"))
    base = f"{m['copy_base_url']}/{a.release}"
    wheels = {}  # filename -> entry
    locks = {}
    for s in SETS:
        report = json.load(open(os.path.join(a.out, f"report-{s}.json")))
        source = {}
        for item in report["install"]:
            di = item["download_info"]
            hashes = di.get("archive_info", {}).get("hashes", {})
            sha = hashes.get("sha256") or di.get("archive_info", {}).get("hash", "sha256=").split("=", 1)[1]
            source[norm(item["metadata"]["name"])] = (item["metadata"]["name"], item["metadata"]["version"], di["url"], sha)
        lines = [
            f"# Exact Python packages for the {s} set, linux aarch64, CPython 3.11.",
            f"# Generated by TroyJ/frigate-build-deps tools/wheelhouse.py from python/{s}-cp311-aarch64.lock;",
            "# each file is a release file of TroyJ/frigate-build-deps, checked by sha256. Do not edit.",
        ]
        seen = set()
        for fn in sorted(os.listdir(os.path.join(a.out, s))):
            if not fn.endswith(".whl"):
                continue
            path = os.path.join(a.out, s, fn)
            key = norm(fn.split("-")[0])
            if key not in source:
                sys.exit(f"{s}: {fn} is not in pip's report")
            seen.add(key)
            name, version, url, src_sha = source[key]
            sha = sha256_file(path)
            e = wheels.get(fn)
            if e is None:
                e = {
                    "id": f"wheel:{fn}",
                    "kind": "python-wheel",
                    "name": name,
                    "version": version,
                    "release": a.release,
                    "asset": fn,
                    "sha256": sha,
                    "size": os.path.getsize(path),
                    "licence": "see the wheel's .dist-info",
                    "used_by": [],
                    "sets": [],
                    "path": path,
                }
                if url.endswith(".whl") and src_sha == sha:
                    e["original_url"] = url
                else:
                    e["built_from"] = "source archive, compiled in Debian 12 with CPython 3.11 (tools/build_wheelhouse.sh)"
                    e["source_url"] = url
                    e["source_sha256"] = src_sha
                wheels[fn] = e
            elif e["sha256"] != sha:
                sys.exit(f"{fn}: two sets built different files")
            e["sets"].append(s)
            for u in (["pi-image", "test-devcontainer"] if s != "dev" else ["test-devcontainer"]):
                if u not in e["used_by"]:
                    e["used_by"].append(u)
            lines.append(f"{name} @ {base}/{fn} --hash=sha256:{sha}")
        missing = set(source) - seen
        if missing:
            sys.exit(f"{s}: no wheel for {sorted(missing)}")
        locks[s] = "\n".join(lines) + "\n"

    os.makedirs("python/fork", exist_ok=True)
    for s, text in locks.items():
        with open(os.path.join("python/fork", os.path.basename(FORK_TARGET[s])), "w") as f:
            f.write(text)

    if a.upload:
        try:
            out = subprocess.run(["gh", "release", "view", a.release, "-R", REPO, "--json", "assets"],
                                 check=True, capture_output=True, text=True).stdout
            existing = {x["name"] for x in json.loads(out)["assets"]}
        except subprocess.CalledProcessError:
            built = sum(1 for e in wheels.values() if "built_from" in e)
            notes = (f"Python wheelhouse for Troy's Frigate fork: linux aarch64, CPython 3.11 (Debian 12). "
                     f"{len(wheels)} wheels, {sum(e['size'] for e in wheels.values()) / 1e6:.0f} MB; "
                     f"{built} compiled here from PyPI source archives, the rest exactly as PyPI (or the project) serves them.\n\n"
                     "Each wheel carries its licence in its .dist-info. Sources, sha256s and which set uses each: manifest.json. "
                     "The fork installs them from python/fork/*.lock (copied into docker/main/), every file checked by sha256.")
            with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False) as f:
                f.write(notes)
            subprocess.run(["gh", "release", "create", a.release, "-R", REPO, "--title", a.release, "--notes-file", f.name, "--target", "main"], check=True)
            existing = set()
        todo = [e["path"] for e in wheels.values() if e["asset"] not in existing]
        for i in range(0, len(todo), 20):
            subprocess.run(["gh", "release", "upload", a.release, "-R", REPO] + todo[i:i + 20], check=True)
        print(f"uploaded {len(todo)} wheel(s), {len(existing)} already there")

    for e in wheels.values():
        e.pop("path")
    m["files"] = [e for e in m["files"] if not (e["kind"] == "python-wheel" and e["release"] == a.release)]
    m["files"] += sorted(wheels.values(), key=lambda e: e["asset"].lower())
    with open("manifest.json", "w") as f:
        json.dump(m, f, indent=1)
        f.write("\n")
    total = sum(e["size"] for e in wheels.values())
    print(f"{len(wheels)} wheels, {total / 1e6:.0f} MB; locks: " + ", ".join(f"{s} {locks[s].count(chr(10)) - 3}" for s in SETS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
